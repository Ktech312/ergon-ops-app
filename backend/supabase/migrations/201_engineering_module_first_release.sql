-- Migration 201: Engineering/Product Development module, first release
-- (decision D14). Design doc: PRODUCT_ENGINEERING_MODULE_DESIGN.md
-- (Queue B8) -- revalidated against the CURRENT schema before writing
-- this (2026-09-23), same discipline as migration 200 (Support). Two
-- concrete facts checked directly rather than assumed from the design
-- doc's own illustrative schema:
--   1. `product_catalog` (migration 013, workspace-scoped by migration
--      176) already has its own real `workspace_id` column and its own
--      `guard_workspace_id_mutation()` trigger -- `product_requests`
--      follows the exact same root-table shape (own workspace_id,
--      directly listable), matching `product_catalog`/`projects`, not a
--      derived-workspace child table.
--   2. `product_catalog`'s own write policy (migration 176) is
--      `is_app_admin() or has_role('manager')` ONLY -- `engineering` has
--      no direct catalog write access today. The design doc's own §6
--      flags "who may trigger the Catalog write" as genuinely
--      undecided -- resolved here as: `engineering` (or an app admin)
--      triggers release through a dedicated, audited
--      `release_product_request()` RPC that performs the catalog write
--      as SECURITY DEFINER, rather than broadening `product_catalog`'s
--      own raw-table RLS to a role that has no reason to write to the
--      catalog directly outside this one controlled path. Matches this
--      schema's own repeated preference for a controlled RPC over
--      widened raw RLS (e.g. `catalog_price_change_requests`).
--   3. `catalog_number` is a plain, manually-entered, unique-per-workspace
--      text field today (confirmed via `createCatalogItem`'s own client
--      code, `src/persistence.ts`) -- not auto-generated by a ref
--      counter. `release_product_request()`'s "new product" mode
--      therefore takes an explicit `p_catalog_number` parameter rather
--      than inventing a new auto-numbering scheme that would diverge
--      from how every other catalog item is created.
--
-- Two of the design doc's own §6 open permission questions are resolved
-- explicitly here, not left ambiguous:
--   - Submission is open to ANY active workspace member (the design
--     doc's own "recommended yes... submission is lower-stakes than
--     review" reasoning, and matches this schema's existing precedent
--     for low-risk actions like Tasks being open to any member).
--   - Review/status-transition/release actions are gated to
--     `engineering`/`product_development`/an app admin, matching the
--     read/write split their existing Inventory permissions already
--     imply (design doc §6, "recommended, not decided" -- decided here).
--
-- Explicitly OUT of scope for this release (unchanged from the design
-- doc's own §7): the Support-case handoff link (Support now exists,
-- migration 200, but this module deliberately does not add that FK
-- yet -- a real, small, additive follow-up, not attempted in this
-- already-large batch); a formal structured requirements schema (stays
-- free text, matching `bundle_components`' own still-open precedent).

begin;

-- ============================================================
-- Section 1 -- product_requests. Root table, own workspace_id, stamped
-- server-side via resolve_caller_workspace_id() in the same trigger that
-- generates request_number ("PR-<year>-####", workspace-scoped ref
-- counter -- identical shape to migration 200's support_case_ref_counters).
-- The optional source_project_id, when supplied, is cross-checked against
-- the caller's own resolved workspace, same containment discipline as
-- migration 200's project_id check.
-- ============================================================

create table if not exists public.product_requests (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id),
  request_number text not null,
  title text not null check (char_length(btrim(title)) > 0),
  source_project_id uuid references public.projects(id),
  source_client_name text,
  requested_by_email text not null,
  status text not null default 'submitted' check (status in (
    'submitted', 'requirements_review', 'technical_review', 'prototyping',
    'release_ready', 'released', 'declined', 'on_hold'
  )),
  requirements text,
  released_catalog_item_id uuid references public.product_catalog(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, request_number)
);

create index if not exists idx_product_requests_workspace_id on public.product_requests(workspace_id);
create index if not exists idx_product_requests_status on public.product_requests(workspace_id, status);
create index if not exists idx_product_requests_source_project on public.product_requests(source_project_id);

create table if not exists public.product_request_ref_counters (
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  year integer not null,
  next_seq integer not null default 1,
  primary key (workspace_id, year)
);

alter table public.product_request_ref_counters enable row level security;

create policy "workspace members read product_request_ref_counters"
  on public.product_request_ref_counters for select to authenticated
  using (public.is_workspace_member(workspace_id));

create or replace function public.assign_product_request_ref()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_workspace_id uuid;
  v_project_workspace_id uuid;
  ref_year integer := extract(year from pg_catalog.now())::integer;
  seq integer;
begin
  v_workspace_id := public.resolve_caller_workspace_id();

  if new.source_project_id is not null then
    v_project_workspace_id := (select workspace_id from public.projects where id = new.source_project_id);
    if v_project_workspace_id is null then
      raise exception 'The selected source project was not found.';
    end if;
    if v_project_workspace_id <> v_workspace_id then
      raise exception 'That project does not belong to your workspace.';
    end if;
  end if;

  new.workspace_id := v_workspace_id;

  if new.request_number is null then
    insert into public.product_request_ref_counters as prrc (workspace_id, year, next_seq)
    values (v_workspace_id, ref_year, 2)
    on conflict (workspace_id, year) do update set next_seq = prrc.next_seq + 1
    returning next_seq - 1 into seq;

    new.request_number := 'PR-' || ref_year || '-' || pg_catalog.lpad(seq::text, 4, '0');
  end if;

  new.updated_at := pg_catalog.now();
  return new;
end;
$$;

revoke all on function public.assign_product_request_ref() from public;

drop trigger if exists product_requests_assign_ref on public.product_requests;
create trigger product_requests_assign_ref
  before insert on public.product_requests
  for each row execute function public.assign_product_request_ref();

