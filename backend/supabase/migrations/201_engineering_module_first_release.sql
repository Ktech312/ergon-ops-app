-- ============================================================
-- Section 3 -- create_product_request(). Open to any active workspace
-- member (design doc §6).
-- ============================================================

create or replace function public.create_product_request(
  p_title text,
  p_requirements text default null,
  p_source_project_id uuid default null,
  p_source_client_name text default null
)
returns public.product_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := auth.uid();
  v_actor_email text;
  v_request public.product_requests;
begin
  if v_actor_id is null then
    raise exception 'Must be signed in to submit a product request';
  end if;
  if p_title is null or char_length(btrim(p_title)) = 0 then
    raise exception 'A title is required';
  end if;

  select email into v_actor_email from auth.users where id = v_actor_id;
  if v_actor_email is null then
    raise exception 'Could not resolve the signed-in user''s email';
  end if;

  insert into public.product_requests (title, requirements, source_project_id, source_client_name, requested_by_email)
  values (btrim(p_title), nullif(btrim(coalesce(p_requirements, '')), ''), p_source_project_id, nullif(btrim(coalesce(p_source_client_name, '')), ''), v_actor_email)
  returning * into v_request;

  insert into public.product_request_reviews (product_request_id, kind, notes, reviewed_by_email, new_status)
  values (v_request.id, 'status_change', 'Request submitted.', v_actor_email, 'submitted');

  return v_request;
end;
$$;

revoke all on function public.create_product_request(text, text, uuid, text) from public;
revoke execute on function public.create_product_request(text, text, uuid, text) from anon;
grant execute on function public.create_product_request(text, text, uuid, text) to authenticated;

