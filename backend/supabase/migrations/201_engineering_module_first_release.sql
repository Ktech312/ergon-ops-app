create table if not exists public.product_request_reviews (
  id uuid primary key default gen_random_uuid(),
  product_request_id uuid not null references public.product_requests(id) on delete cascade,
  kind text not null check (kind in ('technical_review', 'prototype_test', 'release_readiness', 'status_change')),
  outcome text check (outcome in ('pass', 'fail', 'needs_revision')),
  notes text,
  previous_status text,
  new_status text,
  reviewed_by_email text not null,
  -- clock_timestamp(), not now() -- migration 198's own already-found bug
  -- (an audit log's timestamp must reflect the real moment each row is
  -- written, not freeze at the surrounding transaction's start time; this
  -- only differs from now() when two rows are written in the same
  -- transaction, exactly what this migration's own canonical test does
  -- and what real multi-step review flows can also do in a single RPC
  -- call, e.g. log_product_request_review's own review-row-then-
  -- status-change-row pair).
  reviewed_at timestamptz not null default clock_timestamp()
);

create index if not exists idx_product_request_reviews_request on public.product_request_reviews(product_request_id, reviewed_at desc);

alter table public.product_request_reviews enable row level security;

create policy "workspace members read product_request_reviews"
  on public.product_request_reviews for select to authenticated
  using (public.is_workspace_member(public.product_request_owner_workspace_id(product_request_id)));

