-- ============================================================
-- Section 5 -- log_product_request_review(). technical_review/
-- prototype_test only -- release_readiness is written exclusively by
-- release_product_request() below, matching migration 200's own
-- discipline of keeping the "big" transition in its own dedicated
-- function. A review's outcome automatically advances (or does not
-- advance) the request's own status, logged as a SEPARATE, immediately
-- following status_change row in the SAME transaction -- both rows
-- exist, so "why did the status change" is always answerable from the
-- review row sitting right next to it, but "what's the current status"
-- never requires re-deriving it from review history.
-- ============================================================

create or replace function public.log_product_request_review(
  p_product_request_id uuid,
  p_kind text,
  p_outcome text,
  p_notes text default null
)
returns public.product_request_reviews
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := auth.uid();
  v_actor_email text;
  v_request public.product_requests;
  v_review public.product_request_reviews;
  v_new_status text;
begin
  if v_actor_id is null then
    raise exception 'Must be signed in to log a review';
  end if;
  if p_kind not in ('technical_review', 'prototype_test') then
    raise exception 'log_product_request_review only accepts technical_review or prototype_test -- use release_product_request() for release_readiness';
  end if;
  if p_outcome not in ('pass', 'fail', 'needs_revision') then
    raise exception 'outcome must be pass, fail, or needs_revision';
  end if;

  select email into v_actor_email from auth.users where id = v_actor_id;
  if v_actor_email is null then
    raise exception 'Could not resolve the signed-in user''s email';
  end if;

  select * into v_request from public.product_requests where id = p_product_request_id for update;
  if v_request.id is null then
    raise exception 'Product request not found';
  end if;
  if not public.is_active_workspace_member(v_request.workspace_id) then
    raise exception 'Not an active member of this request''s workspace';
  end if;
  if not public.can_review_product_requests() then
    raise exception 'Only engineering, product development, or an admin may log a review';
  end if;
  if v_request.status in ('released', 'declined') then
    raise exception 'Cannot log a review against a % request', v_request.status;
  end if;

  if p_kind = 'technical_review' then
    v_new_status := case p_outcome
      when 'pass' then 'prototyping'
      when 'fail' then 'declined'
      when 'needs_revision' then 'requirements_review'
    end;
  else
    -- prototype_test: pass moves it forward to release_ready; fail/
    -- needs_revision stay in prototyping so a retry can be logged
    -- without forcing a manual status move first.
    v_new_status := case p_outcome
      when 'pass' then 'release_ready'
      else 'prototyping'
    end;
  end if;

  insert into public.product_request_reviews (product_request_id, kind, outcome, notes, reviewed_by_email)
  values (p_product_request_id, p_kind, p_outcome, nullif(btrim(coalesce(p_notes, '')), ''), v_actor_email)
  returning * into v_review;

  if v_new_status is distinct from v_request.status then
    insert into public.product_request_reviews (product_request_id, kind, notes, reviewed_by_email, previous_status, new_status)
    values (p_product_request_id, 'status_change', 'Automatic, from ' || p_kind || ' outcome: ' || p_outcome || '.', v_actor_email, v_request.status, v_new_status);

    update public.product_requests set status = v_new_status where id = p_product_request_id;
  end if;

  return v_review;
end;
$$;

revoke all on function public.log_product_request_review(uuid, text, text, text) from public;
revoke execute on function public.log_product_request_review(uuid, text, text, text) from anon;
grant execute on function public.log_product_request_review(uuid, text, text, text) to authenticated;

-- ============================================================
-- Section 6 -- change_product_request_status(). Manual moves not driven
-- by a review outcome -- e.g. product_development moving a request into
-- requirements_review, putting it on_hold, or declining it outright at
-- any pre-release point. Deliberately rejects 'released' (only reachable
-- via release_product_request()) and rejects moving FROM 'released'/
-- 'declined' at all (both are terminal in this release -- no reopen
-- concept for product requests, unlike Support's cases).
-- ============================================================

create or replace function public.change_product_request_status(
  p_product_request_id uuid,
  p_new_status text,
  p_note text default null
)
returns public.product_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := auth.uid();
  v_actor_email text;
  v_request public.product_requests;
  v_previous_status text;
begin
  if v_actor_id is null then
    raise exception 'Must be signed in to change a product request''s status';
  end if;
  if p_new_status not in ('submitted', 'requirements_review', 'technical_review', 'prototyping', 'on_hold', 'declined') then
    raise exception 'Invalid target status: % (use release_product_request() to reach released)', p_new_status;
  end if;

  select email into v_actor_email from auth.users where id = v_actor_id;
  if v_actor_email is null then
    raise exception 'Could not resolve the signed-in user''s email';
  end if;

  select * into v_request from public.product_requests where id = p_product_request_id for update;
  if v_request.id is null then
    raise exception 'Product request not found';
  end if;
  if not public.is_active_workspace_member(v_request.workspace_id) then
    raise exception 'Not an active member of this request''s workspace';
  end if;
  if not public.can_review_product_requests() then
    raise exception 'Only engineering, product development, or an admin may change a request''s status';
  end if;
  if v_request.status in ('released', 'declined') then
    raise exception 'Cannot change the status of a % request', v_request.status;
  end if;
  if p_new_status = v_request.status then
    raise exception 'Product request is already %', p_new_status;
  end if;

  v_previous_status := v_request.status;

  update public.product_requests set status = p_new_status where id = p_product_request_id;

  insert into public.product_request_reviews (product_request_id, kind, notes, reviewed_by_email, previous_status, new_status)
  values (p_product_request_id, 'status_change', nullif(btrim(coalesce(p_note, '')), ''), v_actor_email, v_previous_status, p_new_status);

  select * into v_request from public.product_requests where id = p_product_request_id;
  return v_request;
end;
$$;

revoke all on function public.change_product_request_status(uuid, text, text) from public;
revoke execute on function public.change_product_request_status(uuid, text, text) from anon;
grant execute on function public.change_product_request_status(uuid, text, text) to authenticated;

-- ============================================================
-- Section 7 -- release_product_request(). Only from 'release_ready'.
-- mode='new' inserts a real product_catalog row (SECURITY DEFINER,
-- bypassing product_catalog's own manager/admin-only write RLS by
-- design -- see this file's own header); mode='update' updates an
-- EXISTING catalog item, cross-checked to belong to the SAME workspace.
-- Either way this is the ONLY place released_catalog_item_id is ever
-- set, and the only place a request reaches status='released'.
-- ============================================================

create or replace function public.release_product_request(
  p_product_request_id uuid,
  p_mode text,
  p_existing_catalog_item_id uuid default null,
  p_catalog_number text default null,
  p_product_name text default null,
  p_sales_description text default null,
  p_technical_description text default null,
  p_category text default null,
  p_default_sell_price numeric default 0,
  p_notes text default null
)
returns public.product_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := auth.uid();
  v_actor_email text;
  v_request public.product_requests;
  v_catalog_item_id uuid;
  v_existing_workspace_id uuid;
begin
  if v_actor_id is null then
    raise exception 'Must be signed in to release a product request';
  end if;
  if p_mode not in ('new', 'update') then
    raise exception 'mode must be new or update';
  end if;

  select email into v_actor_email from auth.users where id = v_actor_id;
  if v_actor_email is null then
    raise exception 'Could not resolve the signed-in user''s email';
  end if;

  select * into v_request from public.product_requests where id = p_product_request_id for update;
  if v_request.id is null then
    raise exception 'Product request not found';
  end if;
  if not public.is_active_workspace_member(v_request.workspace_id) then
    raise exception 'Not an active member of this request''s workspace';
  end if;
  if not (public.is_app_admin(auth.uid()) or public.has_role('engineering')) then
    raise exception 'Only engineering or an admin may release a product request';
  end if;
  if v_request.status <> 'release_ready' then
    raise exception 'Only a release_ready request can be released (current status: %)', v_request.status;
  end if;

  if p_mode = 'new' then
    if p_catalog_number is null or char_length(btrim(p_catalog_number)) = 0 then
      raise exception 'catalog_number is required to release a new catalog item';
    end if;
    insert into public.product_catalog (workspace_id, catalog_number, product_name, sales_description, technical_description, category, default_sell_price)
    values (
      v_request.workspace_id,
      btrim(p_catalog_number),
      coalesce(nullif(btrim(coalesce(p_product_name, '')), ''), v_request.title),
      nullif(btrim(coalesce(p_sales_description, '')), ''),
      nullif(btrim(coalesce(p_technical_description, '')), ''),
      nullif(btrim(coalesce(p_category, '')), ''),
      coalesce(p_default_sell_price, 0)
    )
    returning id into v_catalog_item_id;
  else
    if p_existing_catalog_item_id is null then
      raise exception 'existing_catalog_item_id is required for mode=update';
    end if;
    select workspace_id into v_existing_workspace_id from public.product_catalog where id = p_existing_catalog_item_id;
    if v_existing_workspace_id is null then
      raise exception 'Catalog item not found';
    end if;
    if v_existing_workspace_id <> v_request.workspace_id then
      raise exception 'That catalog item does not belong to this request''s workspace';
    end if;
    update public.product_catalog
    set product_name = coalesce(nullif(btrim(coalesce(p_product_name, '')), ''), product_name),
        sales_description = coalesce(nullif(btrim(coalesce(p_sales_description, '')), ''), sales_description),
        technical_description = coalesce(nullif(btrim(coalesce(p_technical_description, '')), ''), technical_description),
        category = coalesce(nullif(btrim(coalesce(p_category, '')), ''), category),
        default_sell_price = coalesce(p_default_sell_price, default_sell_price),
        updated_at = now()
    where id = p_existing_catalog_item_id;
    v_catalog_item_id := p_existing_catalog_item_id;
  end if;

  update public.product_requests
  set status = 'released', released_catalog_item_id = v_catalog_item_id
  where id = p_product_request_id
  returning * into v_request;

  insert into public.product_request_reviews (product_request_id, kind, outcome, notes, reviewed_by_email, previous_status, new_status)
  values (p_product_request_id, 'release_readiness', 'pass', nullif(btrim(coalesce(p_notes, '')), ''), v_actor_email, 'release_ready', 'released');

  return v_request;
end;
$$;

revoke all on function public.release_product_request(uuid, text, uuid, text, text, text, text, text, numeric, text) from public;
revoke execute on function public.release_product_request(uuid, text, uuid, text, text, text, text, text, numeric, text) from anon;
grant execute on function public.release_product_request(uuid, text, uuid, text, text, text, text, text, numeric, text) to authenticated;

-- ============================================================
-- Section 8 -- notification_rules: register product_request_reviewed so
